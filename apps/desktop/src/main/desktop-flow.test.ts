test('shop menus, photos, live finance permissions, superusers and monthly payments persist safely',async()=>{
  const directory=mkdtempSync(path.join(tmpdir(),'pos-management-features-')),file=path.join(directory,'pos.sqlite');
  const auth=new AuthStore(file,{encrypt:async value=>Buffer.from(value),decrypt:async value=>value.toString()},true);
  let management=new ManagementStore(file,true);
  const sales=new SalesStore(file,path.join(directory,'recovery.sqlite'),value=>Buffer.from(value));
  const base={id:'',kind:'shop' as const,name:'Second shop',phone:'03001234567',passport:'',identity:'',pricePaisa:0,quantity:0,shopId:'main-shop'};
  try{
    await auth.initialize();management.seed(await auth.cashierVerifier('Fixture123!'));
    const rootLogin=await auth.login('superuser','PosSuper123!'),adminLogin=await auth.login('admin','PosAdmin123!');
    assert.ok(rootLogin.ok);assert.ok(adminLogin.ok);const root=rootLogin.user,admin=adminLogin.user;
    assert.equal(root.role,'superuser');
    assert.throws(()=>management.list(admin,'admin',''),/Superuser/);
    const adminRecord={...base,kind:'admin',name:'New admin',username:'new.admin'};
    const verifier=await auth.cashierVerifier('NewAdmin123!');
    assert.throws(()=>management.save(admin,adminRecord,verifier),/Superuser/);
    management.save(root,adminRecord,verifier);
    const created=await auth.login('new.admin','NewAdmin123!');assert.ok(created.ok);assert.equal(created.user.role,'admin');
    await auth.changePassword(created.user.id,'NewAdmin123!','ChangedAdmin123!',()=>true);
    assert.ok((await auth.login('new.admin','ChangedAdmin123!')).ok);
    management.remove(root,'admin',created.user.id);assert.equal(auth.user(created.user.id),null);
    assert.throws(()=>management.list(created.user,'shop',''),/Inactive/);
    management.save(admin,base);const branch=management.list(admin,'shop','Second')[0];
    const cashierProfile=management.list(admin,'cashier','Demo cashier')[0];
    const cashierLogin=await auth.login('demo','PosDemo123!');assert.ok(cashierLogin.ok);const cashier=cashierLogin.user;
    assert.equal(cashier.manageCreditsExpenses,false);
    const image='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aWQAAAABJRU5ErkJggg==';
    const item={...base,kind:'menu',name:'Photo meal',pricePaisa:500,image};
    assert.throws(()=>management.save(admin,{...item,shopId:undefined}));
    assert.throws(()=>management.save(admin,{...item,image:'data:image/svg+xml;base64,PHN2Zz4='}));
    assert.throws(()=>management.save(admin,{...item,image:'data:image/png;base64,YWJj'}));
    management.save(admin,item);management.save(admin,{...item,name:'Other shop meal',shopId:branch.id});
    const mainItem=management.list(admin,'menu','Photo')[0],otherItem=management.list(admin,'menu','Other shop')[0];
    assert.equal(sales.menu(cashier,'Photo')[0].image,image);
    assert.equal(sales.menu(cashier,'Other shop').length,0);
    assert.throws(()=>sales.favourite(cashier,otherItem.id,true));
    const request={operationId:randomUUID(),customerType:'walk-in',creditorId:null,receivedMinor:500,lines:[{itemId:otherItem.id,quantity:1,unitPrice:500}]};
    assert.equal(sales.save(cashier,request).ok,false);
    const customer=management.list(admin,'creditor','')[0];
    const credit={...request,lines:[{itemId:mainItem.id,quantity:1,unitPrice:500}],customerType:'creditor',creditorId:customer.id,receivedMinor:0};
    assert.equal(sales.save(cashier,credit).ok,false);assert.throws(()=>sales.creditors(cashier,''));
    assert.throws(()=>management.save(cashier,{...base,kind:'creditor'}));
    const expense={operationId:randomUUID(),date:businessDate(new Date()),category:'Supplies',description:'Paper',paidVia:'cash',amountMinor:100};
    const normalExpense=sales.saveExpense(cashier,expense);
    assert.ok(normalExpense.ok);
    assert.equal(normalExpense.expense.shopId,'main-shop');
    assert.throws(()=>sales.expenses(cashier,expense.date,expense.date,'main-shop'));
    management.save(admin,{...cashierProfile,phone:base.phone,manageCreditsExpenses:true});
    assert.equal(auth.user(cashier.id)?.manageCreditsExpenses,true);
    assert.ok(sales.save(cashier,credit).ok);assert.ok(sales.saveExpense(cashier,expense).ok);
    management.save(cashier,{...base,kind:'creditor',name:'Cashier customer'});
    assert.equal(management.list(cashier,'shop','').length,1);
    const recovery={operationId:randomUUID(),creditorId:customer.id,date:expense.date,amountMinor:100,shopId:branch.id};
    assert.equal(sales.recoverCredit(cashier,recovery).ok,false);
    assert.ok(sales.recoverCredit(cashier,{...recovery,shopId:'main-shop'}).ok);
    management.save(admin,{...cashierProfile,phone:base.phone,manageCreditsExpenses:false});
    assert.throws(()=>sales.creditorAccount(cashier,customer.id));
    assert.ok(sales.saveExpense(cashier,{...expense,operationId:randomUUID()}).ok);
    assert.ok(sales.saveExpense(cashier,expense).ok,'previous committed expense can still be confirmed');
    management.save(admin,{...base,kind:'payment',name:'FoodPanda',paymentCategory:'online'});
    const method=sales.paymentMethods(cashier).find(row=>row.name==='FoodPanda')!;
    const order={...request,operationId:randomUUID(),paymentMethodId:method.id,lines:[{itemId:mainItem.id,quantity:1,unitPrice:500}]};
    assert.equal(sales.save(cashier,{...order,receivedMinor:501}).ok,false);
    const paidSale=sales.save(cashier,order);assert.ok(paidSale.ok);assert.equal(paidSale.sale.paymentMethod?.name,'FoodPanda');
    assert.equal(sales.history(admin,{start:'2000-01-01',end:'2099-12-31',type:'cash'}).some(row=>row.id===order.operationId),false);
    management.remove(admin,'payment',method.id);
    assert.equal(sales.save(cashier,{...order,operationId:randomUUID()}).ok,false);
    assert.ok(sales.save(cashier,order).ok,'retry keeps the original payment method snapshot');
    management.save(admin,{...base,kind:'recurring',name:'November salary',expenseType:'Salary',employeeId:cashier.id,startMonth:'2026-11',pricePaisa:300000});
    const recurring=management.list(admin,'recurring','')[0];
    assert.throws(()=>management.monthly(cashier,'2026-11'));
    assert.throws(()=>management.monthly(admin,'2026-13'));
    assert.equal(management.monthly(admin,'2026-10').length,0);
    assert.equal(management.monthly(admin,'2026-11')[0].paid,false);
    management.setPaid(admin,recurring.id,'2026-11',true);management.setPaid(admin,recurring.id,'2026-11',true);
    management.save(admin,{...recurring,pricePaisa:350000});
    assert.equal(management.monthly(admin,'2026-11')[0].pricePaisa,300000);
    assert.equal(management.monthly(admin,'2026-12')[0].paid,false);
    assert.equal(management.monthly(admin,'2026-12')[0].pricePaisa,350000);
    management.close();management=new ManagementStore(file,true);
    assert.equal(management.monthly(root,'2026-11')[0].paid,true);
    management.remove(admin,'recurring',recurring.id);
    assert.equal(management.monthly(admin,'2026-11').length,1);
    assert.equal(management.monthly(admin,'2026-12').length,1,'viewed pending obligations survive removal');
    management.setPaid(admin,recurring.id,'2026-11',false);
    assert.equal(management.monthly(admin,'2026-11')[0].paid,false);
    assert.equal(management.monthly(admin,'2027-01').length,0);
  }finally{sales.close();management.close();auth.close();rmSync(directory,{recursive:true,force:true});}
});

test('admin setup connects cashier authentication, checkout, expenses, credit recovery and reports',async()=>{
  const directory=mkdtempSync(path.join(tmpdir(),'pos-connected-')),file=path.join(directory,'pos.sqlite');
  const auth=new AuthStore(file,{encrypt:async value=>Buffer.from(value),decrypt:async value=>value.toString()},true);
  const management=new ManagementStore(file,true);
  let sales=new SalesStore(file,path.join(directory,'recovery.sqlite'),value=>Buffer.from(value));
  try{
    await auth.initialize();
    const login=await auth.login('admin','PosAdmin123!');assert.ok(login.ok);const admin=login.user;
    const base={id:'',kind:'cashier' as const,name:'Connected cashier',phone:'03001234567',passport:'',identity:'',pricePaisa:0,quantity:0,shopId:'main-shop',manageCreditsExpenses:true};
    management.save(admin.role,{...base,username:'connected.cashier'},await auth.cashierVerifier('Connected123!'));
    management.save(admin.role,{...base,kind:'creditor',name:'Connected customer'});
    management.save(admin.role,{...base,kind:'menu',name:'Connected meal',pricePaisa:12345,quantity:10});
    const cashierLogin=await auth.login('connected.cashier','Connected123!');assert.ok(cashierLogin.ok);const cashier=cashierLogin.user;
    const item=sales.menu(cashier,'Connected')[0],creditor=sales.creditors(cashier,'Connected')[0];
    sales.favourite(cashier,item.id,true);
    const sale=sales.save(cashier,{operationId:randomUUID(),customerType:'creditor',creditorId:creditor.id,receivedMinor:2345,lines:[{itemId:item.id,quantity:1,unitPrice:item.priceMinor}]});assert.ok(sale.ok);
    const date=businessDate(new Date());
    assert.ok(sales.saveExpense(cashier,{operationId:randomUUID(),date,category:'Supplies',description:'Connected expense',paidVia:'online',amountMinor:500}).ok);
    assert.equal(sales.creditorAccount(admin,creditor.id).outstanding,10000);
    const repayment=sales.recoverCredit(admin,{operationId:randomUUID(),creditorId:creditor.id,date,amountMinor:4000,shopId:'main-shop'});assert.ok(repayment.ok);
    sales.close();sales=new SalesStore(file,path.join(directory,'recovery.sqlite'),value=>Buffer.from(value));
    assert.equal(sales.menu(cashier,'Connected')[0].favourite,true);
    assert.equal(sales.history(admin,{start:date,end:date,type:'all'})[0].total,12345);
    assert.equal(sales.history(admin,{start:date,end:date,type:'cash'}).length,0);
    assert.equal(sales.history(admin,{start:date,end:date,type:'creditor'})[0].cashierId,cashier.id);
    assert.equal(sales.expenses(admin,date,date)[0].cashierId,cashier.id);
    assert.equal(sales.repayments(admin,date,date)[0].id,repayment.repayment.id);
    const account=sales.creditorAccount(admin,creditor.id);
    assert.equal(account.sales[0].id,sale.sale.id);assert.equal(account.outstanding,6000);
    assert.throws(()=>management.remove(admin.role,'creditor',creditor.id));
    assert.throws(()=>sales.history(cashier,{start:date,end:date,type:'all'}));
    const profile=management.list(admin.role,'cashier','Connected')[0];
    management.remove(admin.role,'cashier',profile.id);
    assert.equal((await auth.login('connected.cashier','Connected123!')).ok,false);
    assert.throws(()=>sales.menu(cashier,''));
    assert.equal(sales.history(admin,{start:date,end:date,type:'all'})[0].cashierName,'Connected cashier');
  }finally{sales.close();management.close();auth.close();rmSync(directory,{recursive:true,force:true});}
});
